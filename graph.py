def 다음문서(후보: list[str], 질문: str, 읽음: list[str], 태그: str) -> str:
    """후보 중 하나를 고른다. 격리의 반대편 — 읽은 내용이 다음 선택지를 만든다.

    수업 3-K 가 조사관 바깥에 떼어 둔 도구다. 바깥에 있으니 따로 불러 볼 수 있다.
    이게 없으면 조사관은 후보 목록의 맨 앞을 집는데, corpus.json 의 링크가 정렬돼 있어
    결과적으로 '가나다순 첫 글자' 를 읽는다. 실제로 치매 질문에 «고혈압» 이 딸려 왔다.
    """
    if not 후보:
        return ""
    if 스텁모드 or len(후보) == 1:
        return 후보[0]

    답 = 부르기(
        고르기프롬프트.format(
            질문=질문,
            읽음="  ".join(f"«{x}»" for x in 읽음) or "(없음)",
            후보="\n".join(f"- {c}" for c in 후보),
        ),
        태그,
    ).strip().strip("«»\"' ")

    # 코드가 검사한다 — 모델은 후보에 없는 제목을 지어낸다 (수업 3-E)
    for c in 후보:
        if c == 답:
            return c
    for c in 후보:
        if c in 답 or 답 in c:
            return c
    return 후보[0]                    # 못 알아들었으면 원래 방식으로 물러난다


def 후보목록(읽음: list[str], 피하기: set[str]) -> list[str]:
    """물러나는 길 두 겹 — 후보가 0이 되면 조사관이 아무것도 못 하고 끝나기 때문."""
    본것 = set(읽음)
    후보 = list(dict.fromkeys(          # 여러 문서가 같은 곳을 가리키면 제목이 겹친다. 순서는 지킨다
        d for r in 읽음 for d in 링크.get(r, []) if d in 문서 and d not in 본것
    ))
    후보 = [d for d in 후보 if d not in 피하기]
    if 후보:
        return 후보
    전체 = [d for d in 문서 if d not in 읽음 and d not in 피하기]   # ① 링크가 막히면 전체에서
    if 전체:
        return 전체
    return [d for d in 문서 if d not in 읽음]                        # ② 그것도 막히면 구역을 푼다


