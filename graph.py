def JSON떼기(raw: str) -> dict:
    """방어 3단 (수업 3-E) — ① JSON 부분만 떼어 내고 ② 실패하면 빈 딕셔너리로 떨어뜨린다.
    ③ 키마다 기본값은 부르는 쪽에서 준다. '모델이 아무것도 제대로 못 줬을 때
    무엇으로 돌아갈 것인가' 를 먼저 정해 놓아야 빠뜨리지 않는다."""
    m = re.search(r"\{.*\}", raw or "", re.S)
    if not m:
        return {}
    try:
        return json.loads(m.group())
    except json.JSONDecodeError:
        return {}


