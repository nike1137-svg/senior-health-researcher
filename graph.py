    꼬리 = f" · ⚠️ 한마디로 인용 빗나감 {빗나간인용}" if 빗나간인용 else ""
    줄 = _log(s, f"⑤ 종합   {len(절들)}절 {len(보고서):,}자{꼬리}")
    알리기(종류="종합", 한마디로=한마디로, 근거=한마디로근거)
