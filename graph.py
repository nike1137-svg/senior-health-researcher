def 평가(s: 상태) -> dict:
    """지표 계산은 metrics.py 가 한다. 이 노드는 상태를 넘기고 로그 한 줄을 남긴다.

    규칙이 두 군데 있으면 한쪽만 고쳐도 숫자가 움직인다 — 과제가 든 첫 번째 사고가 그것이다.
    """
    계량 = metrics.재기(
        {**s, "코퍼스이름": 코퍼스이름, "스위치": dict(설정["스위치"])},
        접기,
    )
    경보 = metrics.경보들(계량)
    줄 = _log(
        s,
        f"⑥ 평가   근거율 {계량['근거율']}% · 격리율 {계량['격리율']}% · "
        f"중복 {계량['중복률']}% · 편중 {계량['편중']}% · 절당 {계량['절당글자']}자 · "
        + ("경보 없음 ✅" if not 경보 else "⚠️ " + " · ".join(경보)),
    )
    return {"계량": 계량, "로그": [줄]}


