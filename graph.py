def 팬아웃(s: 상태):
    """같은 갈림길 함수가 팬아웃과 그냥 통과를 겸한다."""
    idxs = s.get("보내기", [])
    if not idxs:
        return "점검"

    목차 = s["목차"]
    이미읽힌 = {d for sec in s.get("sections", []) for d in sec.get("읽음", [])}
    # 절 번호로 찾는다. 제목으로 찾으면 제목이 같은 절의 조사관이 남의 원고를 이어받는다.
    직전 = {sec["번호"]: sec for sec in s.get("sections", [])}

    보냄 = []
    for i in idxs:
        # 구역 — 코디네이터가 아는 정보로만 만든다.
        # 1바퀴엔 남의 시작문서, 2바퀴엔 이미 읽힌 문서 전부까지. 뒤쪽 바퀴일수록 목록이 강해진다.
        if 설정["스위치"]["구역"]:
            피하기 = {t["시작문서"] for j, t in enumerate(목차) if j != i} | 이미읽힌
        else:
            피하기 = set()
        보냄.append(
            Send(
                "조사",
                {
                    "질문": s["질문"],
                    "번호": i,
                    "절": 목차[i],
                    "예산": 설정["절예산"],       # 이번 바퀴에 새로 읽을 수. 바퀴마다 다시 채워진다
                    "피하기": sorted(피하기),
                    "prior": 직전.get(i, {}),
                    "바퀴": s["바퀴"],
                },
            )
        )
    return 보냄


