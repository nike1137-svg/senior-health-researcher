def 만들기():
    g = StateGraph(상태)
    g.add_node("기획", 기획)
    g.add_node("배치", 배치)
    g.add_node("조사", 조사)
    g.add_node("점검", 점검)
    g.add_node("종합", 종합)
    g.add_node("평가", 평가)

    g.add_edge(START, "기획")
    g.add_edge("기획", "배치")
    g.add_conditional_edges("배치", 팬아웃, ["조사", "점검"])
    g.add_edge("조사", "점검")
    g.add_conditional_edges("점검", 루프, ["배치", "종합"])
    g.add_edge("종합", "평가")
    g.add_edge("평가", END)
    return g.compile()


def 실행(질문: str) -> dict:
    return 만들기().invoke({"질문": 질문}, {"recursion_limit": 50})


