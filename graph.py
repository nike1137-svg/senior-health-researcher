def _인용밀도(sec: dict) -> float:
    # 문장은 metrics.py 의 규칙으로 센다. 전에는 여기서 마침표만 따로 셌는데,
    # 그러면 문장 세는 규칙이 두 군데가 된다 — 과제가 든 첫 번째 사고와 같은 종류.
    # max(1, …) 는 본문이 비었을 때 0 으로 나누는 것을 막는다.
    문장수 = max(1, len(metrics.문장나누기(sec["본문"])))
    return len(sec.get("인용", [])) / 문장수


def 접기(sections: list[dict]) -> dict[int, dict]:
    """재위임으로 같은 절이 두 벌 올라온다. 어느 쪽을 남길지가 config 의 결정.

    ★ 열쇠는 절 **번호**다. 제목이 아니다.
      처음엔 제목을 열쇠로 썼다. T1 에서 코디네이터가 네 절 제목을 전부 「당뇨병」 으로 지었고,
      그러자 서로 다른 조사관 넷의 원고가 하나로 합쳐져 셋이 보고서에서도 지표에서도 사라졌다.
      오류 메시지는 한 줄도 없었다 — 로그의 「읽음 3.0×1」 로만 드러났다 (REPORT 부록 F).
    """
    방식 = 설정["두번째원고"]["방식"]
    남은: dict[int, dict] = {}
    for sec in sections:
        k = sec["번호"]
        if k not in 남은:
            남은[k] = sec
        elif 방식 == "덮어쓰기":
            남은[k] = sec                                  # 수업 방식 — 마지막 것이 이긴다
        else:                                              # "인용밀도"
            if _인용밀도(sec) >= _인용밀도(남은[k]):
                남은[k] = sec
    return 남은


def 점검(s: 상태) -> dict:
    latest = 접기(s.get("sections", []))
    목차 = [dict(t) for t in s["목차"]]

    # 종료 조건의 이중 통제 — 예산 기준을 바깥에, 내용 기준을 안에.
    if not 설정["스위치"]["재위임"] or s["바퀴"] >= 설정["바퀴상한"]:
        줄 = _log(s, f"④ 점검   {s['바퀴']}바퀴 · 종료(예산)")
        알리기(종류="점검", 바퀴=s["바퀴"], 종료="예산", 다시=[])
        return {"보내기": [], "종료": "예산", "로그": [줄]}

    # 절 번호로 찾는다. 제목으로 찾으면 제목이 같은 절들이 한 절의 신고로 함께 판단된다.
    빈칸 = [i for i in range(len(목차)) if not latest.get(i, {}).get("충분", False)]
    if not 빈칸:
        줄 = _log(s, f"④ 점검   {s['바퀴']}바퀴 · 종료(충분)")
        알리기(종류="점검", 바퀴=s["바퀴"], 종료="충분", 다시=[])
        return {"보내기": [], "종료": "충분", "로그": [줄]}

    for i in 빈칸:
        이전 = latest.get(i, {})
        읽은것 = "», «".join(이전.get("읽음", [])) or "없음"
        # 겨냥. 이 문장이 없으면 2바퀴가 1바퀴와 같은 선택을 한다.
        # 원래 물음은 지운다. 덮어쓰면 조사관이 자기 몫을 잃고 전체 질문에 답하러 돌아간다.
        원래물음 = 목차[i]["지시"].split("  (재위임:")[0]
        목차[i]["지시"] = (
            f"{원래물음}  (재위임: 지난번에 «{읽은것}» 를 읽었지만 "
            f"{이전.get('부족사유','부족')}. 그쪽을 겨냥해 새 문서를 찾아라.)"
        )

    줄 = _log(s, f"④ 점검   {s['바퀴']}바퀴 · 빈 칸 {len(빈칸)}개 → 재위임")
    알리기(종류="점검", 바퀴=s["바퀴"], 종료="", 다시=빈칸)
    return {"목차": 목차, "보내기": 빈칸, "종료": "", "로그": [줄]}


def 루프(s: 상태) -> str:
    return "배치" if s.get("보내기") else "종합"


