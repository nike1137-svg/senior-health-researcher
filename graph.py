    꼬리 = " · ⚠️ JSON 파싱 실패 (전부 기본값)" if 파싱실패 else ""
    줄 = [_log(s, f"① 기획   카드 {len(카드)}장 {본글자:,}자 → {len(목차)}절{꼬리}")]
