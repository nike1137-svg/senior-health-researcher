"""baseline.py — 혼자 하는 대조군

    나누지 않는 쪽. 한 명이 같은 자료에서 같은 읽기 예산만큼 읽고 보고서 한 편을 혼자 쓴다.
    팀과 견주면 「분업이 값을 했나」 가 보인다.

실행
    python baseline.py --대조표                 팀 vs 혼자 설정 대조표 + 예산을 다 쓰는지 (0원)
    python baseline.py --질문 "..." [--코퍼스 corpus_full.json]    실제 실행 (돈 씀)

────────────────────────────────────────────────────────────
공정 조건 — 과제 원문
    「대조군에는 같은 자료 · 모델 · 도구 · 같은 읽기 예산을 줍니다. 예산을 다 쓰는지 확인하세요.
     중간에 멈추면 이긴 것이 아니라 상대를 묶어 둔 것입니다」

맞춘 것 (작성자 승인 2026-09-23)
    같은 자료 · 같은 모델 · 같은 도구(graph.read_one · graph.다음문서 · graph.후보목록)
    같은 읽기 예산 — 절수 × 절예산 (기본 4 × 3 = 12건)

다르게 둔 것
    A 읽는 방식 — 역할 없이 읽는다. 수업이 read_one 에 질문만 넘긴 것과 같다.
                   역할은 분업이 주는 것이라, 혼자에게 없는 게 곧 재려는 차이다
    B 시작 문서 — 코디네이터가 본 것과 같은 카드를 보고 하나 고른다
    C 보고서 형식 — 팀과 같다: 면책 · 한마디로(+근거) · «문서명» 인용 · 분량(절수 × 문장 범위)
                    분량을 자유로 두면 짧게 쓰고 끝낼 수 있다 — 약한 상대가 된다
    D 멈추지 않게 — 모델이 후보에 없는 제목을 답하면 후보 첫 번째로 물러난다 (graph.다음문서)

수업이 밟은 함정 (3-AB)
    「대조군은 열두 건 예산 중 서너 건만 읽고 멈췄다 … 그 상태로 재면 팀이 압승한다.
     당연하다 — 상대는 예산의 3분의 1만 쓴 것」
    그래서 --대조표 가 가짜 응답기로 0원에 끝까지 돌려 실제로 몇 건을 읽는지 먼저 본다.
"""
