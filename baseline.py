시작프롬프트 = """질문: {질문}

당신은 혼자서 이 질문에 답할 보고서 한 편을 씁니다. 아직 자료를 한 건도 읽지 않았습니다.
아래 카드(제목 + 본문 앞부분)를 보고 **처음 읽을 문서 하나**를 고르십시오.
카드에 있는 제목만 쓰십시오. 없는 제목을 지어내지 마십시오.

자료 카드 ({문서수}건)
{카드}

아래 JSON 만 출력하십시오. 설명을 붙이지 마십시오.
{{"시작문서": "카드에 있는 제목"}}
"""

쓰기프롬프트 = """당신은 혼자서 보고서 한 편을 씁니다. 목차를 나누거나 다른 사람에게 맡기지 않습니다.

질문: {질문}

아래는 당신이 읽은 문서 {n}건에서 추린 메모입니다. **원문은 이미 손을 떠났습니다.**

{메모}

★ 가장 중요한 규칙 — **문장마다 근거가 된 문서를 «문서명» 형식으로 그 문장 끝에 붙이십시오.**
   인용이 없는 문장은 근거 없이 쓴 문장으로 간주해 버립니다.
   메모에 없는 문서는 인용하지 마십시오. 위 메모에 «» 로 표시된 이름만 쓰십시오.
   예) 치매의 초기 증상으로는 단기 기억 상실이 흔하다 «치매».

1. 보고서 본문을 {최소}~{최대} 문장으로 쓰십시오.
2. 메모에 없는 내용을 지어내지 마십시오. 모르면 안 쓰는 편이 낫습니다.
3. **「한마디로」** — 질문의 답을 **어르신이 읽으실 수 있는 쉬운 말 2~3문장**으로 쓰십시오.
   - 어려운 의학 용어를 쓰지 마십시오. 본문에 없는 내용을 새로 만들지 마십시오.
   - 「한마디로」 안에는 «» 를 쓰지 말고, **「근거」 칸에 쓴 문서 제목을 목록으로** 적으십시오.

아래 JSON 만 출력하십시오. 설명을 붙이지 마십시오.
{{"본문": "...", "한마디로": "...", "근거": ["문서 제목", "문서 제목"]}}
"""


def 예산() -> int:
    """팀과 같은 읽기 예산 — 절수 × 절예산. 팀의 설정이 바뀌면 여기도 따라 바뀐다."""
    return graph.설정["절수"] * graph.설정["절예산"]


def 혼자(질문: str) -> dict:
    """혼자 하는 대조군 한 번. metrics.재기() 가 그대로 받을 수 있는 상태를 돌려준다."""
    문서, 설정 = graph.문서, graph.설정
    고침: list[str] = []

    # ── B 시작 문서 — 코디네이터와 같은 카드를 본다 ────────────────
    카드 = graph.카드목록()
    카드글자 = sum(len(c) for c in 카드)
    if graph.스텁모드:
        시작 = next(iter(문서))
        파싱실패 = False
    else:
        받음 = graph.JSON떼기(graph.부르기(
            시작프롬프트.format(질문=질문, 문서수=len(카드), 카드="\n".join(카드)),
            "혼자_시작",
        ))
        파싱실패 = not 받음
        시작 = (받음.get("시작문서") or "").strip()
        if 시작 not in 문서:
            고침.append(f"시작문서 «{시작}» 은 코퍼스에 없어 바꿨다" if 시작
                      else "시작문서를 못 받아 기본값으로 세웠다")
            시작 = graph._대체문서(set())

    # ── 읽기 — 팀과 같은 도구, 같은 예산. A: 역할 없이 읽는다 ───────
    읽음: list[str] = []
    메모: list[str] = []
    읽은글자 = 0
    빈손수 = 0
    멈춘이유 = "예산을 다 씀"
    for i in range(예산()):
        if not 읽음:
            다음 = 시작
        else:
            후보 = graph.후보목록(읽음, set())          # 혼자라 남의 구역이 없다
            if not 후보:
                멈춘이유 = f"후보가 없어 {len(읽음)}건에서 멈춤"
                break
            # D: 모델이 후보에 없는 제목을 답해도 멈추지 않는다 — 다음문서가 후보 첫 번째로 물러난다
            다음 = graph.다음문서(후보, 질문, 읽음, f"혼자_고르기_{i+1}")
            if not 다음 or 다음 in 읽음:
                멈춘이유 = f"고를 문서가 없어 {len(읽음)}건에서 멈춤"
                break
        m, n = graph.read_one(다음, 질문, "")        # A: 역할 없이
        읽음.append(다음)
        메모.append(f"«{다음}» {m}")
        읽은글자 += n
        if m.strip() == 설정["조사관"]["관련없음"]:
            빈손수 += 1

    # ── 쓰기 — C: 팀과 같은 형식 · 같은 분량 범위 ──────────────────
    절수 = 설정["절수"]
    최소, 최대 = 설정["조사관"]["최소문장"] * 절수, 설정["조사관"]["최대문장"] * 절수
    if graph.스텁모드:
        본문, 한마디로, 받은근거 = "(스텁) " + "\n".join(메모), "(스텁 한마디로)", list(읽음[:1])
    else:
        받음 = graph.JSON떼기(graph.부르기(
            쓰기프롬프트.format(질문=질문, n=len(읽음), 메모="\n\n".join(메모),
                              최소=최소, 최대=최대),
            "혼자_쓰기",
        ))
        파싱실패 = 파싱실패 or not 받음
        본문 = (받음.get("본문") or "").strip()
        한마디로 = (받음.get("한마디로") or "").strip()
        받은근거 = 받음.get("근거") or []
        if isinstance(받은근거, str):
            받은근거 = [받은근거]
        받은근거 = [str(c).strip().strip("«»") for c in 받은근거 if str(c).strip()]

    # 혼자에겐 절이 없으니 「한마디로」 근거는 실제로 읽은 문서여야 한다
    근거 = [c for c in dict.fromkeys(받은근거) if c in 읽음]
    빗나간 = [c for c in dict.fromkeys(받은근거) if c not in 읽음]

    # ── 보고서 — 면책은 팀과 똑같이 맨 앞 ──────────────────────────
    조각 = [f"# {질문}", "", 설정["면책"], ""]
    if 한마디로:
        조각 += ["## 한마디로", "", 한마디로, ""]
        if 근거:
            조각 += ["_근거: " + " · ".join(f"«{c}»" for c in 근거) + "_", ""]
    조각 += ["## 혼자 쓴 보고서", 본문]
    보고서 = "\n".join(조각)

    절 = {
        "번호": 0, "절": "혼자", "역할": "혼자", "시작문서": 시작,
        "본문": 본문, "인용": metrics.인용뽑기(본문), "읽음": 읽음, "새읽음": 읽음,
        "빈손수": 빈손수, "충분": True, "부족사유": "", "한줄": "", "바퀴": 1,
    }
    return {
        "질문": 질문,
        "목차": [{"절": "혼자", "역할": "혼자", "시작문서": 시작, "지시": ""}],
        "sections": [절],
        "바퀴": 1,
        "종료": 멈춘이유,
        # 격리율 — 혼자는 쓰는 사람이 곧 읽는 사람이다. 쓰는 사람이 본 글자 = 카드 + 메모 전부
        "코디글자": 카드글자 + sum(len(x) for x in 메모),
        "읽은글자": 읽은글자,
        "고침": 고침,
        "파싱실패": 파싱실패,
        "한마디로": 한마디로,
        "한마디로근거": 근거,
        "빗나간인용": 빗나간,
        "보고서": 보고서,
        "예산": 예산(),
    }


def 재기(상태: dict) -> dict:
    return metrics.재기(
        {**상태, "코퍼스이름": graph.코퍼스이름, "스위치": {"혼자": True}},
        lambda xs: {x["절"]: x for x in xs},
    )


