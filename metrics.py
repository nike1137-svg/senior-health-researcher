def 규칙확인() -> int:
    """문장·인용 세는 규칙이 이 파일 한 곳에만 있는지 검사한다.

    두 군데 있으면 한쪽만 고쳐도 근거율이 움직인다.
    과제 원문이 든 첫 번째 사고 — 「지표가 좋아진 줄 알았는데 문장 분리 규칙이 바뀐 것」.
    """
    찾을것 = ["def 문장나누기", "def 인용뽑기", "_문장끝", "_인용 = re.compile"]
    파일들 = sorted(p for p in 루트.glob("*.py")) + sorted(루트.glob("tools/*.py"))

    print("■ 문장·인용 규칙이 어디에 있나")
    print(f"{'파일':<16} " + " ".join(f"{x:<16}" for x in 찾을것))
    print("-" * 84)
    합계 = {x: 0 for x in 찾을것}
    for p in 파일들:
        줄들 = p.read_text(encoding="utf-8").splitlines()
        # 줄 맨 앞에서 시작하는 것만 센다. 들여쓴 것은 정의가 아니라 쓰는 쪽이고,
        # 이 검사 코드가 가진 찾을 문자열 목록도 그래서 안 걸린다.
        수 = {x: sum(1 for 줄 in 줄들 if 줄.startswith(x)) for x in 찾을것}
        if not any(수.values()):
            continue
        for x in 찾을것:
            합계[x] += 수[x]
        print(f"{p.name:<16} " + " ".join(f"{수[x]:<16}" for x in 찾을것))

    # ── 둘째 검사: 이름 없이 따로 세는 흔적 ─────────────────────
    # 첫 검사는 정의된 이름만 찾아서, graph.py 의 인용밀도가 `.count(".")` 로
    # 문장을 따로 세던 것을 못 잡았다 (2026-09-23 4-A-3 에서 발견).
    # 그래서 문장·인용을 세는 흔한 모양을 저장소 전체에서 찾는다.
    # 찾을 모양을 문자열 이어 붙이기로 만든 것은, 이 검사 코드 자신이 걸리지 않게 하려는 것이다.
    점 = '"."'
    몰래 = {
        "마침표로 문장 세기": ".count(" + 점 + ")",
        "마침표로 문장 나누기": ".split(" + 점 + ")",
        "따로 만든 문장 분리 정규식": "(?<=" + "[.",
        "따로 만든 인용 정규식": "re.findall(r" + '"' + "«",
    }
    print()
    print("■ 이름 없이 문장·인용을 따로 세는 곳이 있나")
    걸린 = []
    for p in 파일들:
        for i, 줄 in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
            if p.name == "metrics.py" and (줄.startswith("_문장끝") or 줄.startswith("_인용 =")):
                continue                     # 정의 자리는 첫 검사가 센다
            if 줄.lstrip().startswith("#"):
                continue                     # 주석은 코드가 아니다 (설명 속 글자에 걸리지 않게)
            for 뜻, 모양 in 몰래.items():
                if 모양 in 줄:
                    걸린.append(f"{p.name}:{i}  {뜻}  →  {줄.strip()[:60]}")
    for x in 걸린:
        print("  ✗", x)
    if not 걸린:
        print("  없음")

    print()
    탈 = [x for x, n in 합계.items() if n != 1]
    if 탈 or 걸린:
        if 탈:
            print(f"❌ 한 곳에만 있어야 하는데 개수가 다릅니다: "
                  + " · ".join(f"{x} {합계[x]}개" for x in 탈))
        if 걸린:
            print(f"❌ metrics.py 밖에서 문장·인용을 따로 세는 곳이 {len(걸린)}곳 있습니다. "
                  "metrics.문장나누기() · 인용뽑기() 를 쓰게 고치십시오.")
        return 1
    print("✅ 넷 다 metrics.py 한 곳에만 있고, 다른 곳에서 따로 세는 흔적도 없습니다.")
    print("   graph.py 는 metrics 에서 가져다 씁니다.")
    return 0


def 기록보기(n: int = 10, 스텁도: bool = False) -> None:
    """실행 기록 요약.

    스텁 실행은 기본으로 감춘다. LLM 을 한 번도 안 부른 가짜 값이라
    실제 실행과 같은 표에 놓으면 4단계 집계가 오염된다.
    """
    if not 기록파일.exists():
        print(f"{기록파일} 이 없습니다. 아직 실행 기록이 없습니다.")
        return
    전부 = [json.loads(x) for x in 기록파일.read_text(encoding="utf-8").splitlines() if x.strip()]
    스텁 = [r for r in 전부 if r.get("꼬리표") == "스텁"]
    줄들 = 전부 if 스텁도 else [r for r in 전부 if r.get("꼬리표") != "스텁"]

    print(f"{기록파일}")
    print(f"  전체 {len(전부)}건 · 실제 {len(전부)-len(스텁)}건 · 스텁 {len(스텁)}건"
          + ("" if 스텁도 else "  (스텁은 감춤 — 보려면 --스텁도)"))
    print()
    머리 = (f"{'때':<13} {'코퍼스':<17} {'근거율':>6} {'격리율':>6} {'중복률':>6} "
            f"{'편중':>6} {'절글자':>6} {'비용원':>6}  경보")
    print(머리)
    print("-" * 96)
    for r in 줄들[-n:]:
        m = r["계량"]
        경 = 경보들(m)
        꼬 = "[스텁] " if r.get("꼬리표") == "스텁" else ""
        print(f"{m['때'][5:16]:<13} {꼬}{m.get('코퍼스',''):<17} "
              f"{str(m.get('근거율')):>6} {str(m.get('격리율')):>6} "
              f"{str(m.get('중복률')):>6} {str(m.get('편중')):>6} "
              f"{str(m.get('절당글자')):>6} {r.get('비용달러',0)*1450:>6.0f}  "
              f"{'없음 ✅' if not 경 else '⚠️ ' + ' · '.join(경)}")


