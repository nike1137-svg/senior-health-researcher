def 자가시험() -> int:
    실패 = 0
    print("■ 문장 분리 규칙")
    for 글, 기대, 설명 in _시험글:
        실제 = len(문장나누기(글))
        표 = "  " if 실제 == 기대 else "✗ "
        if 실제 != 기대:
            실패 += 1
        print(f"  {표}{설명:<26} 기대 {기대} · 실제 {실제}")

    print("\n■ 같은 글을 두 번 세면 같은 수가 나오는가")
    글 = "\n\n".join(x[0] for x in _시험글)
    a, b = len(문장나누기(글)), len(문장나누기(글))
    표 = "  " if a == b else "✗ "
    if a != b:
        실패 += 1
    print(f"  {표}두 번 세기                 {a} · {b}")

    print("\n■ 인용 뽑기")
    for 글, 기대, 설명 in _인용시험:
        실제 = 인용뽑기(글)
        표 = "  " if 실제 == 기대 else "✗ "
        if 실제 != 기대:
            실패 += 1
        print(f"  {표}{설명:<26} 기대 {기대} · 실제 {실제}")

    print(f"\n■ 절겹침 ({겹침어절}어절 연속)")
    for 본문들, 기대, 설명 in _겹침시험:
        실제, _ = 겹친문장(본문들)
        표 = "  " if 실제 == 기대 else "✗ "
        if 실제 != 기대:
            실패 += 1
        print(f"  {표}{설명:<32} 기대 {기대} · 실제 {실제}")

    print("\n■ 지표표와 코드가 어긋나지 않는가")
    # 지표가 아닌 것(사실·크기)만 여기 적는다. 재기() 가 내는 나머지는 전부 지표표에 있어야 한다.
    # 거꾸로 지표 이름을 여기 적으면, 새 지표를 더하고 표에 안 적어도 이 검사가 못 잡는다.
    지표아님 = {"때", "질문", "코퍼스", "스위치", "바퀴", "종료", "절수",
               "코디글자", "읽은글자", "읽은문서수", "문장수", "보고서글자"}
    가짜 = {"sections": [{"절": "가", "본문": "가 «가».", "읽음": ["가"]}]}
    낸것 = set(재기(가짜, lambda xs: {x["절"]: x for x in xs})) - 지표아님
    표에없음 = sorted(낸것 - set(지표표))
    코드에없음 = sorted(set(지표표) - 낸것)
    if 표에없음 or 코드에없음:
        실패 += 1
        print(f"  ✗ 코드는 내는데 표에 없음: {표에없음}")
        print(f"  ✗ 표에는 있는데 코드가 안 냄: {코드에없음}")
    else:
        print(f"  {'':2}신호·경보 {len(지표표)}개가 표와 코드에 똑같이 있습니다")

    print()
    if 실패:
        print(f"❌ {실패}건 어긋남. 규칙이 바뀌었으니 지금까지 잰 값과 견주지 마십시오.")
    else:
        print("✅ 전부 통과. 문장 분리 · 인용 · 겹침 규칙이 그대로이고 지표표가 코드와 맞습니다.")
    return 1 if 실패 else 0


