# ─────────────────────────────────────────────────────────────
# 절겹침 — 「절끼리 같은 말을 한다」를 센다.
#
#   중복률은 같은 *문서*를 읽었나를 보지, 같은 *말*을 썼나는 안 본다.
#   오늘 세 번(네 절이 같은 말 · 한 줄이 넷 다 「상담하세요」 · 첫머리 질문 되풀이)
#   이 종류가 났는데 지표가 하나도 못 잡았다.
#
#   「거의 같은」 을 판정 모델 없이 세려고 **4어절이 연속으로 똑같은가** 로 정했다.
#   인용 표시와 문장부호는 걷어내고 본다 — 인용 유무로 겹침이 갈리면 안 된다.
# ─────────────────────────────────────────────────────────────
겹침어절 = 4


def _어절들(문장: str) -> list[str]:
    s = _인용.sub(" ", 문장 or "")
    s = re.sub(r"[^\w\s]", " ", s)
    return s.split()


def _조각들(문장: str, n: int) -> set[tuple[str, ...]]:
    w = _어절들(문장)
    return {tuple(w[i:i + n]) for i in range(len(w) - n + 1)}


def 겹친문장(절본문들: list[str], n: int = 겹침어절) -> tuple[int, int]:
    """(다른 절과 n어절 이상 연속으로 똑같은 대목이 있는 문장 수, 전체 문장 수)"""
    절별문장 = [문장나누기(b) for b in 절본문들]
    절별조각 = [set().union(*(_조각들(s, n) for s in ss)) if ss else set() for ss in 절별문장]
    겹침 = 전체 = 0
    for i, ss in enumerate(절별문장):
        남의것 = set().union(*(절별조각[j] for j in range(len(절별조각)) if j != i)) \
            if len(절별조각) > 1 else set()
        for s in ss:
            전체 += 1
            if _조각들(s, n) & 남의것:
                겹침 += 1
    return 겹침, 전체


