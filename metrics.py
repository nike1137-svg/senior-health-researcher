# ★ 문장 분리 규칙 — 이 프로젝트에서 문장을 세는 곳은 여기 하나뿐이다.
#
#   과제 원문이 든 흔한 사고 셋 중 첫째가 이것이다:
#     「지표가 좋아진 줄 알았는데 문장 분리 규칙이 바뀐 것」
#   규칙이 두 군데 있으면 한쪽만 고쳐도 근거율이 움직인다. 그래서 한 곳에 고정하고
#   --자가시험 으로 같은 글에 같은 수가 나오는지 확인한다.
# ─────────────────────────────────────────────────────────────
_문장끝 = re.compile(r"(?<=[.!?])\s+")


def 문장나누기(글: str) -> list[str]:
    """글을 문장 목록으로. 빈 문장은 버린다."""
    if not 글:
        return []
    줄들 = [x for x in re.split(r"\n+", 글) if x.strip()]
    문장: list[str] = []
    for 줄 in 줄들:
        문장 += [x.strip() for x in _문장끝.split(줄) if x.strip()]
    return 문장


# 여는 기호는 « 로 고정하되, 닫는 기호는 모델이 흘리는 것들까지 받는다.
# 실제 보고서에 «뇌경색” 이 나왔고, » 만 세던 규칙이 그걸 놓쳐 근거율이 실제보다 낮게 나왔다.
# 계측기가 틀리면 4단계의 모든 비교가 틀어지므로 여기서 바로잡는다.
_인용 = re.compile(r"«\s*([^«»\n”\"]{1,60}?)\s*(?:»|”|\"|』|〉)")


def 인용뽑기(글: str) -> list[str]:
    """본문에 «» 로 붙은 인용을 뽑는다. 모델이 준 목록이 아니라 글에 실제로 붙은 것을 센다."""
    return _인용.findall(글 or "")


