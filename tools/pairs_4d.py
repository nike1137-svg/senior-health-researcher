"""pairs_4d.py — 4-D 「결과물을 직접 비교하기」 재료 만들기

    python -m tools.pairs_4d        output/4D/ 에 읽을 파일 다섯 개를 만든다 (0원 — 기록에서 뽑기만)

과제 원문 4단계
    ① 나란히 놓고 직접 읽는다. 어느 쪽이 나은지와 그렇게 판단한 이유를 자기 말로 적는다
    ② 마음에 안 드는 대목이 어느 절에서, 어느 자료에서 비롯됐는지 찾는다
    ③ 인용이 제자리에 붙었는지 원문과 대조한다 — 읽은 문서를 엉뚱한 문장에 갖다 붙인 것은 사람만 잡는다

이 도구는 재료만 만든다. 판단 칸은 비워 둔다.
인용 대조의 「원문에서 가장 가까운 대목」 은 낱말이 많이 겹치는 곳을 코드가 고른 **후보**다.
제자리에 붙었는지는 작성자가 읽고 정한다.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

루트 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(루트))
import metrics  # noqa: E402

기록 = 루트 / "output" / "runs.jsonl"
방 = 루트 / "output" / "4D"
확 = "corpus_full.json"

_불용 = {"있습니다", "있다", "합니다", "됩니다", "있으며", "그리고", "또한", "이는", "경우", "때문",
        "통해", "대한", "위해", "것이", "것은", "수도", "있을", "어머님이", "어머님의", "어머니가"}


def _읽기():
    D = {}
    for x in 기록.read_text(encoding="utf-8").splitlines():
        if not x.strip():
            continue
        r = json.loads(x)
        p = r.get("꼬리표", "").split("|")
        if p[0] in ("본실행", "시운전"):
            D[(p[1], p[2], p[3], int(p[4]))] = r
    return D


def _질문(qid):
    qs = json.loads((루트 / "data" / "questions.json").read_text(encoding="utf-8"))["questions"]
    return next(q["text"] for q in qs if q["id"] == qid)


def _한줄지표(r):
    m = r["계량"]
    인 = sum(len(metrics.인용뽑기(s.get("본문", ""))) for s in r["절들"])
    return (f"근거율 {m['근거율']}% · 문장 {m['문장수']} · 인용 {인}곳 · "
            f"보고서 {m['보고서글자']:,}자 · 인용 0곳 절 {m['경보_인용0곳절']}")


def _절들(r):
    """최종 보고서에 실린 순서대로 (재위임이 없었으므로 1바퀴 원고가 곧 최종본)."""
    return sorted([s for s in r["절들"] if s.get("바퀴", 1) == 1], key=lambda s: s["번호"])


def _머리(r):
    """보고서에서 한마디로 · 머리말 · 맺음말만 뽑는다."""
    글 = r.get("보고서", "")
    한 = re.search(r"## 한마디로\n\n(.*?)\n\n", 글, re.S)
    근 = re.search(r"_근거: (.*?)_", 글)
    끝 = 글.rstrip().split("\n")[-1]
    return (한.group(1).strip() if 한 else "(없음)"), (근.group(1) if 근 else "(없음)"), 끝


def _판단칸(물음들):
    줄 = ["", "---", "", "## ✍️ 판단 — 작성자가 자기 말로", ""]
    for q in 물음들:
        줄 += [f"**{q}**", "", "- ", ""]
    return 줄


def _보고서전체(r, 이름):
    한, 근, 끝 = _머리(r)
    줄 = [f"### {이름}", "", f"> {_한줄지표(r)}", "", f"**한마디로** — {한}", "", f"_근거: {근}_", ""]
    for s in _절들(r):
        n = len(metrics.인용뽑기(s.get("본문", "")))
        줄 += [f"#### {s['번호']+1}. [{s['역할']}] «{s['절']}»  — 인용 {n}곳 · 읽음 {' · '.join(s.get('읽음') or [])}",
               "", s.get("본문", "").strip() or "(비어 있음)", ""]
    # 마지막 줄이 절 본문이면 맺음말이 없는 보고서다 (혼자) — 본문을 두 번 찍지 않는다
    if 끝 and not 끝.startswith("#") and not any(끝.strip() in (s.get("본문") or "") for s in _절들(r)):
        줄 += [f"**맺음말** — {끝}", ""]
    return 줄


# ─────────────────────────────────────────────────────────────
# 인용 대조 — 인용이 붙은 문장마다 원문에서 낱말이 가장 많이 겹치는 대목을 후보로
# ─────────────────────────────────────────────────────────────
def _낱말(문장):
    s = re.sub(r"«[^»]*»", " ", 문장)
    return [t for t in re.findall(r"[가-힣A-Za-z0-9]{2,}", s) if t not in _불용]


def _가까운대목(문장, 원문):
    낱 = _낱말(문장)
    if not 낱 or not 원문:
        return 0.0, "", []
    조각 = [c.strip() for c in metrics.문장나누기(원문) if len(c.strip()) > 15]
    최고 = (0.0, "", [])
    for c in 조각:
        겹 = [t for t in 낱 if t[:max(2, len(t) - 1)] in c]
        점 = len(겹) / len(낱)
        if 점 > 최고[0]:
            최고 = (점, c, 겹)
    return 최고


def _인용대조(절, 문서):
    줄 = ["", "### 🔍 인용 대조 — 인용 붙은 문장마다 원문에서 가장 가까운 대목 (코드가 고른 **후보**)", "",
          "> 겹친 낱말 비율이 높다고 제자리인 것이 아니고, 낮다고 엉뚱한 것도 아니다. **읽고 판단한다.**",
          "> 판단 칸: ✅ 제자리 · ⚠️ 엉뚱한 문서 · ❓ 원문에 없는 말", ""]
    for i, 문장 in enumerate(metrics.문장나누기(절.get("본문", "")), 1):
        인들 = metrics.인용뽑기(문장)
        if not 인들:
            continue
        for 인 in dict.fromkeys(인들):
            점, 대목, 겹 = _가까운대목(문장, 문서.get(인, ""))
            줄 += [f"**문장 {i}** — {문장}", "",
                   f"- 인용: «{인}» {'(읽은 문서)' if 인 in (절.get('읽음') or []) else '⚠️ 이 조사관이 안 읽은 문서'}",
                   f"- 원문 후보 (낱말 {len(겹)}/{len(_낱말(문장))} 겹침): …{대목[:220]}…" if 대목 else "- 원문 후보: 겹치는 대목 없음",
                   f"- 판단: ", ""]
    return 줄


# ─────────────────────────────────────────────────────────────
def 만들기():
    D = _읽기()
    문서 = json.loads((루트 / "data" / 확).read_text(encoding="utf-8"))["docs"]
    방.mkdir(parents=True, exist_ok=True)
    공통 = ["> 이 파일은 `output/runs.jsonl` 기록에서 뽑았다. **에이전트는 판정하지 않았다.**",
           "> 지표는 참고용이다 — 과제: 「지표는 명백한 실패를 거르는 데만 쓰고 순위표로 쓰지 않는다」", ""]
    만든 = []

    # 1. M7 1회차 기본 vs 역할끔 — 네 절이 같고 역할만 다르다
    a, b = D[(확, "기본", "M7", 1)], D[(확, "역할끔", "M7", 1)]
    줄 = ["# 4-D 재료 1 — M7 1회차 · 기본 vs 역할끔", "", f"**질문** — {_질문('M7')}", "", *공통,
          "**원문 ①** 나란히 놓고 직접 읽는다 · **G-5 ④** 역할을 끄면 제도를 덜 쓰나", "",
          "네 절이 **같은 자료**에서 출발했다. 다른 것은 **역할뿐**이다.", "",
          f"| | 기본 | 역할끔 |", "|---|---|---|",
          f"| 지표 | {_한줄지표(a)} | {_한줄지표(b)} |"]
    for sa, sb in zip(_절들(a), _절들(b)):
        줄.append(f"| {sa['번호']+1}절 | [{sa['역할']}] «{sa['절']}» | [{sb['역할']}] «{sb['절']}» |")
    줄 += [""]
    for sa, sb in zip(_절들(a), _절들(b)):
        줄 += [f"## {sa['번호']+1}절 «{sa['절']}»", "",
               f"**기본 · {sa['역할']}** — 인용 {len(metrics.인용뽑기(sa['본문']))}곳", "", sa["본문"].strip(), "",
               f"**역할끔 · {sb['역할']}** — 인용 {len(metrics.인용뽑기(sb['본문']))}곳", "", sb["본문"].strip(), ""]
    for 이름, r in (("기본", a), ("역할끔", b)):
        한, 근, _ = _머리(r)
        줄 += [f"**{이름} 한마디로** — {한}  _(근거: {근})_", ""]
    줄 += _판단칸(["「치매관리법」 절 — 역할이 있을 때 제도를 더 구체적으로 썼는가",
                  "보고서 전체로는 어느 쪽이 나은가, 왜"])
    만든.append(("1_M7_기본_vs_역할끔.md", 줄))

    # 2 · 4. 기본 vs 혼자
    for 번호, q, 붙임 in ((2, "M1", "오늘 계속 쓴 질문"), (4, "T1", "혼자가 분량을 지킨 유일한 편")):
        a, b = D[(확, "기본", q, 1)], D[(확, "혼자", q, 1)]
        줄 = [f"# 4-D 재료 {번호} — {q} 1회차 · 기본(팀) vs 혼자", "", f"**질문** — {_질문(q)}", "", *공통,
              f"**원문 ①** 나란히 놓고 직접 읽는다 · **G-5 ③** 혼자 vs 팀 — {붙임}", "",
              "| | 팀 (기본) | 혼자 |", "|---|---|---|",
              f"| 지표 | {_한줄지표(a)} | {_한줄지표(b)} |", "",
              "## 먼저 — 한마디로만 나란히", ""]
        for 이름, r in (("팀", a), ("혼자", b)):
            한, 근, _ = _머리(r)
            줄 += [f"**{이름}** — {한}", "", f"_근거: {근}_", ""]
        줄 += ["## 보고서 전체", ""] + _보고서전체(a, "팀 (기본)") + _보고서전체(b, "혼자")
        줄 += _판단칸(["어르신 보호자가 읽는다면 어느 쪽이 나은가", "그렇게 판단한 이유 (근거율은 잊고)"])
        만든.append((f"{번호}_{q}_기본_vs_혼자.md", 줄))

    # 3. M1 기본 치매관리법 절 — 1회차 vs 2회차
    줄 = ["# 4-D 재료 3 — M1 기본 · 「치매관리법」 절 · 1회차 vs 2회차", "", f"**질문** — {_질문('M1')}", "", *공통,
          "**원문 ②** 어느 절 · 어느 자료에서 비롯됐나 · **원문 ③** 인용이 제자리에 붙었나 · **G-5 ⑥**", "",
          "같은 절이 **같은 문서 셋을 읽었는데** 한 번은 인용이 있고 한 번은 없다.", "",
          "> ⚠️ **조사관의 메모는 기록에 없다.** 기록에는 읽은 문서 목록과 원고만 남겼다.",
          "> 그래서 「메모부터 비었나, 원고에서 빠뜨렸나」 는 이 기록으로 가를 수 없다.",
          "> 편집자는 절 본문에 손대지 않으므로(수업 3-S ①안) **원고가 곧 최종본의 그 절**이다.", ""]
    for 회 in (1, 2):
        r = D[(확, "기본", "M1", 회)]
        절 = next(s for s in _절들(r) if s["절"] == "치매관리법")
        목 = r["목차"][절["번호"]]
        최종에있나 = 절["본문"].strip()[:60] in r["보고서"]
        줄 += [f"## {회}회차", "",
               f"- **기획** — 역할 `{목['역할']}` · 시작문서 «{목['시작문서']}» · 물음: {목.get('지시') or '(없음)'}",
               f"- **읽은 문서** — {' → '.join(절.get('읽음') or [])}",
               f"- **인용** — {len(metrics.인용뽑기(절['본문']))}곳 {metrics.인용뽑기(절['본문']) or ''}",
               f"- **한 줄** (한마디로 재료) — {절.get('한줄') or '(없음)'}",
               f"- **최종본에 그대로 실렸나** — {'예' if 최종에있나 else '⚠️ 아니오'}",
               f"- **코드가 기획을 고친 것** — {r.get('고침') or '없음'}", "",
               "**원고 (= 최종본의 이 절)**", "", 절["본문"].strip(), ""]
        if 회 == 1:
            줄 += _인용대조(절, 문서)
    줄 += _판단칸(["2회차에 인용이 0곳이 된 것 — 원고를 읽어 보면 어디서 갈린 것 같은가",
                  "1회차 인용 4곳 — 제자리에 붙었는가 (위 표의 「판단」 칸을 채우셔도 됩니다)"])
    만든.append(("3_M1_치매관리법절_1회차_vs_2회차.md", 줄))

    # 5. T1 뇌졸중 절 — 왜 생겼나
    줄 = ["# 4-D 재료 5 — T1 기본 · 「치료 담당:뇌졸중」 절", "", f"**질문** — {_질문('T1')}", "", *공통,
          "**원문 ②** 마음에 안 드는 대목이 어느 절 · 어느 자료에서 비롯됐나", "",
          "당뇨·눈 질문에 **뇌졸중 치료** 절이 들어왔고 두 회차 모두 인용 0곳이다.",
          "수업 3-T 에서 거의 반드시 생긴다고 한 **질문 범위를 벗어난 절**로 보인다.", "",
          "**어디서 비롯됐나를 가를 단서** — 기획이 뇌졸중을 골랐나, 아니면 코드가 겹침을 고치다 넣었나", ""]
    for 회 in (1, 2):
        r = D[(확, "기본", "T1", 회)]
        줄 += [f"## {회}회차", "", "**목차 전체**", ""]
        for i, t in enumerate(r["목차"]):
            줄.append(f"{i+1}. [{t['역할']}] «{t['절']}» ← 시작문서 «{t['시작문서']}» · 물음: {t.get('지시') or '(없음)'}")
        줄 += ["", f"**코드가 기획을 고친 것** — {r.get('고침') or '없음'}", ""]
        절 = next((s for s in _절들(r) if s["절"] == "뇌졸중"), None)
        if 절:
            줄 += [f"**뇌졸중 절** — 읽은 문서 {' → '.join(절.get('읽음') or [])} · 인용 "
                   f"{len(metrics.인용뽑기(절['본문']))}곳", "", 절["본문"].strip(), ""]
    줄 += _판단칸(["이 절은 어디서 비롯됐나 — 기획? 코드의 대체? 조사관?",
                  "이 절이 보고서에 있는 것이 읽는 사람에게 해로운가, 그냥 군더더기인가"])
    만든.append(("5_T1_뇌졸중절_어디서.md", 줄))

    for 이름, 줄 in 만든:
        (방 / 이름).write_text("\n".join(줄) + "\n", encoding="utf-8")
        print(f"  {방 / 이름}  ({len(chr(10).join(줄)):,}자)")


if __name__ == "__main__":
    만들기()
